// Writes src/player-script.generated.ts: hls.min.js from the installed hls.js package, as a string.
// A task is bundled into one file and its VM carries no node_modules for pure-JS packages, so the
// player script must travel inside the code, not be read from disk at run time. Never a CDN.
// The output is not committed (see .gitignore): it is made from the lockfile's hls.js at every build.

import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const out = new URL('../src/player-script.generated.ts', import.meta.url);
const { version } = require('hls.js/package.json');
const script = await readFile(require.resolve('hls.js/dist/hls.min.js'), 'utf8');

const text = [
  `// Generated by scripts/embed-player-script.mjs from hls.js ${version} (Apache-2.0,`,
  '// https://github.com/video-dev/hls.js). Do not edit and do not commit: every build makes it again.',
  '',
  `export const PLAYER_SCRIPT_VERSION: string = ${JSON.stringify(version)};`,
  `export const PLAYER_SCRIPT: string = ${JSON.stringify(script)};`,
  '',
].join('\n');

// Unchanged output keeps its mtime, so `tsc -b` does not rebuild the package for nothing.
const current = await readFile(out, 'utf8').catch(() => null);
if (current !== text) await writeFile(out, text);
